package WhileLoopPractice;

import java.util.Scanner;

public class CodeCheaf {

	public static void main(String[] args) {
		Scanner sc = new Scanner(System.in);
		int t = sc.nextInt();

		for (int i = 0; i < t; i++) {

			int a = sc.nextInt();
			int b = sc.nextInt();
			int c = sc.nextInt();
			int d = sc.nextInt();
			int e = sc.nextInt();
			System.out.println(a + " " + b + " " + c + " " + d + " " + e);
		}
	}
}
